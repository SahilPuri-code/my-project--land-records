import { requireApiUser } from "@/lib/http";
import { createPdf } from "@/lib/pdf";
import { getRecordBundle } from "@/lib/service";
import { formatDate } from "@/lib/api-client";

export const runtime = "nodejs";

export async function GET(
  request: Request,
  { params }: { params: Promise<{ recordId: string }> }
) {
  const auth = await requireApiUser();
  if ("error" in auth) return auth.error;
  const { recordId } = await params;
  const bundle = getRecordBundle(recordId);
  if (!bundle) return new Response("Record not found", { status: 404 });
  const type = new URL(request.url).searchParams.get("type") || "summary";
  const { record, owners, documents, issues, explanation, receipt, reviews, history } = bundle;
  const score = bundle.trust;

  const lines: string[] = [];
  lines.push("## Property identification");
  lines.push(`ULPIN: ${record.ulpin}`);
  lines.push(`Survey / subdivision: ${record.survey_number}/${record.subdivision_number}`);
  lines.push(`Village / taluka / district: ${record.village} / ${record.taluka} / ${record.district}, ${record.state}`);
  lines.push(`Owner(s): ${owners.map((o) => `${o.name} (${(o.share * 100).toFixed(0)}%)`).join(", ")}`);
  lines.push(`Recorded area: ${record.recorded_area.toLocaleString("en-IN")} m2`);
  lines.push(`Mapped area: ${record.mapped_area.toLocaleString("en-IN")} m2`);
  lines.push(`Land use: ${record.land_use}`);
  lines.push(`Workflow status: ${record.status.replaceAll("_", " ")}`);
  lines.push("---");
  lines.push("## Parcel Trust Score");
  lines.push(`Overall: ${record.trust_score}/100 (${record.status.replaceAll("_", " ")})`);
  if (explanation) {
    for (const component of explanation.components) {
      lines.push(
        `${component.label}: ${component.score}/100 x ${component.weight}% = ${component.weighted} points`
      );
      for (const d of component.deductions) lines.push(`  - ${d.reason}: -${d.points} (${d.detail})`);
    }
    lines.push(`Provisional score: ${explanation.provisional ? "Yes — evidence is incomplete." : "No."}`);
    lines.push(`Last calculated: ${formatDate(score?.calculated_at)}`);
  }
  lines.push("---");
  lines.push(`## Validation issues (${issues.length})`);
  if (issues.length === 0) lines.push("No inconsistencies were found in the supplied demo evidence.");
  for (const issue of issues) {
    lines.push(`[${issue.severity.toUpperCase()}] ${issue.title} (${issue.rule_code})`);
    lines.push(issue.description);
    lines.push(`Evidence: ${issue.evidence}`);
    lines.push(`Recommended action: ${issue.recommended_action}`);
    lines.push("");
  }
  lines.push("---");
  lines.push("## Linked documents");
  for (const doc of documents) {
    lines.push(`${doc.file_name} (${doc.document_category.replaceAll("_", " ")}) · OCR ${doc.ocr_status}`);
    lines.push(`SHA-256: ${doc.sha256_hash}`);
  }
  if (type === "validation") {
    lines.push("---");
    lines.push("## Validation scope");
    lines.push("Compared: record-of-rights text, cadastral geometry and sample ground evidence.");
    lines.push("Rules: area, owner share, subdivision, duplicate survey, overlap, land use, boundary shift, evidence completeness and OCR confidence.");
  }
  if (history.length) {
    lines.push("---");
    lines.push("## Illustrative 4D history");
    for (const entry of history) {
      lines.push(`${entry.year}: ${entry.description} (${entry.review_status.replaceAll("_", " ")})`);
    }
  }
  if (receipt) {
    lines.push("---");
    lines.push("## Prototype verification receipt");
    lines.push(`Receipt number: ${receipt.receipt_no}`);
    lines.push(`Issued: ${formatDate(receipt.issued_at)}`);
    lines.push(`Snapshot SHA-256: ${receipt.snapshot_hash}`);
  } else {
    lines.push("---");
    lines.push("## Verification");
    lines.push("No verification receipt has been issued for this record.");
  }
  if (reviews.length) {
    lines.push("");
    lines.push("## Review history");
    for (const r of reviews) {
      lines.push(`${formatDate(r.reviewed_at)} · ${r.decision} by ${r.officer_name}: ${r.comments}`);
    }
  }
  lines.push("---");
  lines.push("## Important disclaimer");
  lines.push("This report was generated by the BHUMI 3D hackathon prototype using illustrative demo data. It is not a government-issued land record, legal certificate, or proof of title. AI-assisted findings require review by an authorized human officer.");

  const pdf = createPdf({
    title: type === "validation" ? "Validation Report" : "Property Summary",
    subtitle: `${record.survey_number}/${record.subdivision_number} · ${record.village}, ${record.district}`,
    lines,
    footer: "BHUMI 3D prototype report · illustrative demo data · not a government certificate",
  });
  return new Response(new Uint8Array(pdf), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="bhumi-3d-${type}-${record.survey_number.replace("/", "-")}.pdf"`,
      "Cache-Control": "private, no-store",
    },
  });
}
